/** An image handle within one declaration. Its evaluating renderer owns the rendering resources. */
@Immutable
public class BackdropImage internal constructor(internal val owner: Any, internal val index: Int)

/** The channel used to turn a drawing into coverage. */
public enum class BackdropMaskChannel {
    Alpha,
    Luminance,
}

/** Immutable configuration snapshots generated by dsl-utilities. */
@Immutable public interface BackdropRenderValue

/** A layer declaration generated by dsl-utilities. */
@DslBuilder(supertype = BackdropRenderValue::class)
public interface BackdropLayerDsl {
    public val image: BackdropImage
    @DslValue(initial = "1.0") public var alpha: Float
    @DslValue public var blendMode: BlendMode?
}

/** Ordered image layers. Each layer is built and snapshotted by dsl-utilities. */
@DslBuilder(supertype = BackdropRenderValue::class)
public interface BackdropGroupDsl {
    @DslList(children = [BackdropLayerDsl::class]) public var layers: MutableList<BackdropLayer>
}

/** Restricts implicit receiver lookup to the innermost render declaration. */
@DslMarker
@Target(AnnotationTarget.CLASS, AnnotationTarget.TYPE)
@Retention(AnnotationRetention.BINARY)
public annotation class BackdropRenderDsl

/** Selects receiver outputs. The trailing declaration builds its background in drawing order. */
@BackdropRenderDsl
public class BackdropRenderScope
internal constructor(
    density: Float,
    fontScale: Float,
    size: Size,
    shape: Shape,
    layoutDirection: LayoutDirection,
    resolveStyle: () -> BackdropStyle = { BackdropStyle.Default },
    interactionLightsPresent: () -> Boolean = { true },
) :
    BackdropImageScope(
        density,
        fontScale,
        size,
        shape,
        layoutDirection,
        interactionLightsPresent = interactionLightsPresent,
        resolveStyle = resolveStyle,
    ) {
    /**
     * Creates an independent surface-pixel declaration for [BackdropRenderer]. [style] supplies
     * inherited appearance at use time. Modifier rendering manages window interaction lighting;
     * independent declarations use caller-supplied optical and decoration inputs.
     */
    public constructor(
        density: Density,
        size: Size,
        shape: Shape,
        layoutDirection: LayoutDirection,
        style: () -> BackdropStyle = { BackdropStyle.Default },
    ) : this(
        density.density,
        density.fontScale,
        size,
        shape,
        layoutDirection,
        resolveStyle = style,
        interactionLightsPresent = { false },
    ) {
        require(
            density.density.isFinite() &&
                density.density > 0f &&
                density.fontScale.isFinite() &&
                density.fontScale > 0f,
        ) {
            "Density and font scale must be finite and positive"
        }
        require(
            size.width.isFinite() &&
                size.height.isFinite() &&
                size.width >= 0f &&
                size.height >= 0f,
        ) {
            "Surface size must be finite and non-negative"
        }
    }

    internal var styledSurfaceDeclared: Boolean = false
    internal var surfaceDeclared: Boolean = false

    internal var styleInsets: (() -> BackdropInsets)? = null
    /** Optional foreground selected by [foreground], drawn separately from the background. */
    public var foregroundImage: BackdropImage? = null
        private set

    /**
     * Optional image selected by [export]; the host owns presentation opacity and source export.
     */
    public var exportedImage: BackdropImage? = null
        private set

    public fun foreground(block: BackdropImageScope.() -> Unit) {
        check(!styledSurfaceDeclared) { "Use appendForeground after styledSurface" }
        foregroundImage = image(block)
    }

    /**
     * Composites a transparent-based declaration above the retained foreground. Operations in
     * [block] select the additional image; they preserve the previously selected foreground.
     */
    public fun appendForeground(block: BackdropImageScope.() -> Unit) {
        val previous = foregroundImage
        val addition = image(block)
        foregroundImage = image {
            if (previous != null) draw(previous)
            draw(addition)
        }
    }

    internal fun styledForeground(block: BackdropImageScope.() -> Unit) {
        foregroundImage = image(block)
        styledSurfaceDeclared = true
    }

    /**
     * Selects [image] as the export output. Modifier hosts apply background alpha and publish
     * outward-rounded, pixel-aligned source bounds without sampling padding. Independent renderer
     * hosts own export presentation and source boundaries.
     */
    public fun export(image: BackdropImage = current) {
        checkImage(image)
        exportedImage = image
    }
}

/**
 * Ordered image operations select or composite into [current]. [image] captures a reusable subgraph
 * without changing the surrounding result.
 */
@BackdropRenderDsl
public open class BackdropImageScope
internal constructor(
    density: Float,
    fontScale: Float,
    size: Size,
    public val shape: Shape,
    public val layoutDirection: LayoutDirection,
    internal val graph: MutableList<RenderImageNode> = mutableListOf(),
    private val owner: BackdropGraphOwner = BackdropGraphOwner(size),
    initial: BackdropImage? = null,
    private val interactionLightsPresent: () -> Boolean = { true },
    internal val resolveStyle: () -> BackdropStyle = { BackdropStyle.Default },
) {
    /** Measured surface pixels; declaration reads make graph structure depend on resizing. */
    public val size: Size
        get() {
            if (owner.declaring) owner.readsSize = true
            return owner.size
        }

    internal val readsSize: Boolean
        get() = owner.readsSize

    internal fun updateSize(size: Size) {
        owner.size = size
    }

    internal fun surfaceScope(): BackdropSurfaceScope =
        BackdropSurfaceScope(owner.size, density, shape, layoutDirection, this)

    public val density: Density = Density(density, fontScale)
    /**
     * Whether the receiver's provider contains light sources in its Compose window. Reading this
     * during declaration observes source membership; source movement retains the declaration.
     * Registered sources remain present throughout their release animation, including zero
     * intensity.
     */
    public val hasInteractionLights: Boolean
        get() = interactionLightsPresent()

    /** The original input, independent of the selected result. */
    public val input: BackdropImage =
        if (graph.isEmpty()) add(RenderImageNode.Source) else reference(0)
    public var current: BackdropImage = initial ?: input
        private set

    /** Selects the original input without adding another copy to the composite. */
    public fun source() {
        checkDeclaration()
        current = input
    }

    /** Selects an existing result without compositing it. */
    public fun replace(image: BackdropImage) {
        checkImage(image)
        current = image
    }

    /** Captures a transparent-based subgraph without changing the surrounding result. */
    public fun image(block: BackdropImageScope.() -> Unit): BackdropImage {
        val nested =
            BackdropImageScope(
                density.density,
                density.fontScale,
                owner.size,
                shape,
                layoutDirection,
                graph,
                owner,
                add(RenderImageNode.Empty),
                interactionLightsPresent,
                resolveStyle,
            )
        nested.block()
        return nested.current
    }

    /** Captures an independent layer without changing the surrounding result. */
    public fun layer(block: BackdropImageScope.() -> Unit): BackdropImage =
        add(RenderImageNode.Isolation(image(block).index))

    /** Replaces current with a transparent-based group, applying alpha once to that group. */
    public fun group(alpha: Float = 1f, block: BackdropImageScope.() -> Unit) {
        requireAlpha(alpha)
        val result = image(block)
        current =
            if (alpha == 1f) result
            else
                add(
                    RenderImageNode.Composite(
                        add(RenderImageNode.Empty).index,
                        result.index,
                        alpha,
                        BlendMode.SrcOver,
                    ),
                )
    }

    /**
     * Appends drawing to current. [CompositingStrategy.Offscreen] isolates destination-based
     * blending within this image. Select [CompositingStrategy.Auto] for SrcOver drawing that can
     * compose directly into its consumer; graph alpha and blend operations still apply as a group.
     */
    public fun paint(
        compositingStrategy: CompositingStrategy = CompositingStrategy.Offscreen,
        draw: @BackdropRenderDsl DrawScope.(BackdropRoom) -> Unit,
    ) {
        current =
            add(
                RenderImageNode.Paint(
                    current.index,
                    draw,
                    compositingStrategy = compositingStrategy,
                ),
            )
    }

    /**
     * Appends [paint] drawing clipped to the visible surface, with the same compositing contract.
     */
    public fun paintSurface(
        compositingStrategy: CompositingStrategy = CompositingStrategy.Offscreen,
        draw: @BackdropRenderDsl DrawScope.(BackdropRoom) -> Unit,
    ) {
        current = add(RenderImageNode.Paint(current.index, draw, true, compositingStrategy))
    }

    /** The callback controls input drawing; omit drawContent to replace it. */
    public fun drawWithContent(
        image: BackdropImage = current,
        sampling: BackdropSampling = BackdropSampling.Identity,
        block:
            @BackdropRenderDsl
            DrawScope.(drawContent: DrawScope.() -> Unit, room: BackdropRoom) -> Unit,
    ) {
        checkImage(image)
        current = add(RenderImageNode.DrawWithContent(image.index, sampling, block))
    }

    public fun fill(color: Color): Unit =
        paintSurface(CompositingStrategy.Auto) { room ->
            drawRect(
                color,
                room.extension.originInNode,
                Size(
                    room.size.width + room.extension.left + room.extension.right,
                    room.size.height + room.extension.top + room.extension.bottom,
                ),
            )
        }

    public fun fill(brush: Brush, alpha: Float = 1f) {
        requireAlpha(alpha)
        paintSurface(CompositingStrategy.Auto) { room ->
            drawRect(
                brush,
                room.extension.originInNode,
                Size(
                    room.size.width + room.extension.left + room.extension.right,
                    room.size.height + room.extension.top + room.extension.bottom,
                ),
                alpha = alpha,
            )
        }
    }

    public fun clear(rect: Rect): Unit = paint {
        drawRect(Color.Transparent, rect.topLeft, rect.size, blendMode = BlendMode.Clear)
    }

    public fun clear(path: Path) {
        val frozen = Path().apply { addPath(path) }
        paint { drawPath(frozen, Color.Transparent, blendMode = BlendMode.Clear) }
    }

    public fun effects(block: @BackdropRenderDsl BackdropEffectScope.() -> Unit) {
        current = add(RenderImageNode.Process(current.index, block))
    }

    public fun clip(shape: Shape = this.shape) {
        current = add(RenderImageNode.ShapeClip(current.index, shape))
    }

    public fun clip(path: Path) {
        current = add(RenderImageNode.Clip(current.index, Path().apply { addPath(path) }))
    }

    public fun clipSurface() {
        current = add(RenderImageNode.SurfaceClip(current.index))
    }

    public fun transform(matrix: Matrix) {
        current = add(RenderImageNode.Transform(current.index, Matrix(matrix.values.copyOf())))
    }

    public fun draw(
        image: BackdropImage,
        alpha: Float = 1f,
        blendMode: BlendMode = BlendMode.SrcOver,
    ) {
        checkImage(image)
        requireAlpha(alpha)
        current = add(RenderImageNode.Composite(current.index, image.index, alpha, blendMode))
    }

    /** Replaces current with the ordered list, starting from transparent pixels. */
    public fun layers(block: BackdropGroupDsl.() -> Unit) {
        group {
            for ((image, alpha, mode) in buildBackdropGroup(block).layers) draw(
                image,
                alpha,
                mode ?: BlendMode.SrcOver,
            )
        }
    }

    public fun mask(
        coverage: BackdropImage,
        channel: BackdropMaskChannel = BackdropMaskChannel.Alpha,
        inverse: Boolean = false,
    ) {
        current = masked(current, coverage, channel, inverse)
    }

    private fun masked(
        input: BackdropImage,
        coverage: BackdropImage,
        channel: BackdropMaskChannel,
        inverse: Boolean,
    ): BackdropImage {
        checkImage(input)
        checkImage(coverage)
        require(channel != BackdropMaskChannel.Luminance || isRuntimeShaderSupported()) {
            "Luminance masks require runtime shaders; select alpha coverage explicitly"
        }
        val alpha =
            if (channel == BackdropMaskChannel.Alpha) coverage
            else
                image {
                    replace(coverage)
                    effects {
                        runtimeShaderEffect(
                            "luminance-mask",
                            """
                            uniform shader content;
                            half4 main(float2 p) {
                                half4 c = content.eval(p);
                                half a = clamp(dot(c.rgb, half3(0.2126, 0.7152, 0.0722)), 0.0, 1.0);
                                return half4(a);
                            }
                            """
                                .trimIndent(),
                            "content",
                            BackdropSampling.Identity,
                        ) {}
                    }
                }
        return add(
            RenderImageNode.Mask(input.index, alpha.index, BackdropMaskChannel.Alpha, inverse),
        )
    }

    /** Replaces current with the premultiplied interpolation of the two images. */
    public fun mix(first: BackdropImage, second: BackdropImage, weight: BackdropImage) {
        checkImage(first)
        checkImage(second)
        checkImage(weight)
        group {
            draw(masked(first, weight, BackdropMaskChannel.Alpha, true))
            draw(
                masked(second, weight, BackdropMaskChannel.Alpha, false),
                blendMode = BlendMode.Plus,
            )
        }
    }

    public fun mix(first: BackdropImage, second: BackdropImage, weight: Float) {
        requireAlpha(weight)
        val coverage = image {
            paint { room ->
                drawRect(
                    Color.White,
                    room.extension.originInNode,
                    Size(
                        room.size.width + room.extension.left + room.extension.right,
                        room.size.height + room.extension.top + room.extension.bottom,
                    ),
                    alpha = weight,
                )
            }
        }
        mix(first, second, coverage)
    }

    internal fun deferredPrimitive(
        inputs: List<BackdropImage>,
        resolve: (BackdropGeometry) -> RenderImageNode.Primitive<*>,
    ) {
        inputs.forEach(::checkImage)
        drawPrimitive(
            RenderImageNode.DeferredPrimitive(inputs.toList(), resolve),
            1f,
            BlendMode.SrcOver,
        )
    }

    internal fun drawPrimitive(node: RenderImageNode, alpha: Float, blendMode: BlendMode) {
        draw(add(node), alpha, blendMode)
    }

    internal fun finishDeclaration() {
        owner.declaring = false
    }

    private fun checkDeclaration() {
        check(owner.declaring) { "Graph operations belong to the declaration phase" }
    }

    internal fun checkImage(image: BackdropImage) {
        checkDeclaration()
        validateImage(image)
    }

    internal fun validateImage(image: BackdropImage) {
        require(image.owner === owner && image.index in graph.indices) {
            "Image references belong to one render declaration"
        }
    }

    private fun reference(index: Int): BackdropImage = BackdropImage(owner, index)

    private fun add(node: RenderImageNode): BackdropImage {
        checkDeclaration()
        graph += node
        return reference(graph.lastIndex)
    }
}

internal fun requireAlpha(alpha: Float) {
    require(alpha.isFinite() && alpha in 0f..1f) { "Alpha must be finite and in 0..1" }
}

internal class BackdropGraphOwner(var size: Size) {
    var declaring: Boolean = true
    var readsSize: Boolean = false
}
